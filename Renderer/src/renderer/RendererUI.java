    /**
     * Zooms the map to show all loaded layers.
     * Guards against calling FullExtent on an empty (unloaded) viewer.
     */
    private void btnFullExtentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFullExtentActionPerformed
        if(GIS.getIsEmpty()) return;  // Do nothing if no layers have been loaded yet
        GIS.FullExtent();
    }//GEN-LAST:event_btnFullExtentActionPerformed

    /**
     * Switches the viewer to Zoom interaction mode (rubber-band area zoom
     * and scroll-wheel zoom).
     * Guards against calling setMode on an empty viewer.
     */
    private void btnZoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnZoomActionPerformed
        if(GIS.getIsEmpty()) return;  // Viewer must have at least one layer loaded
        GIS.setMode(TGIS_ViewerMode.Zoom);
    }//GEN-LAST:event_btnZoomActionPerformed

    /**
     * Switches the viewer to Drag (pan) interaction mode so the user can
     * click and drag to pan across the map.
     * Guards against calling setMode on an empty viewer.
     */
    private void btnDragActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDragActionPerformed
        if(GIS.getIsEmpty()) return;  // Viewer must have at least one layer loaded
        GIS.setMode(TGIS_ViewerMode.Drag);
    }//GEN-LAST:event_btnDragActionPerformed

