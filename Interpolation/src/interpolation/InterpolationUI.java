    /**
     * Main Generate button handler: orchestrates the full interpolation workflow.
     *
     * <p>Steps performed on the Swing EDT before spawning the background thread:
     * <ol>
     *   <li>Retrieve source ("temperatures") and polygon ("country") layers by name.</li>
     *   <li>Delete any previous "grid" layer to avoid duplicates.</li>
     *   <li>Compute geographic extent from the polygon layer.</li>
     *   <li>Create and initialise a blank in-memory {@code TGIS_LayerPixel} with
     *       square pixels (aspect ratio correction applied).</li>
     * </ol>
     *
     * <p>Steps performed on the background thread (to keep the EDT free for repaints):
     * <ol>
     *   <li>Dispatch to the selected interpolation method.</li>
     *   <li>Apply a Blue-&gt;Lime-&gt;Red colour ramp via {@code GenerateRamp}.</li>
     *   <li>Clip the output to the country polygon via {@code setCuttingPolygon}.</li>
     *   <li>Add the grid to the viewer and zoom to full extent.</li>
     * </ol>
     */
    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        btnGenerate.setEnabled(false);

        // Retrieve named layers from the loaded project
        src = (TGIS_LayerVector)GIS.Get("temperatures");  // point data source
        plg = (TGIS_LayerVector)GIS.Get("country");       // polygon for extent/clip

        // Remove any previous interpolation result so we start fresh
        if (GIS.Get("grid") != null) {
            GIS.Delete("Grid");
        }

        // Use the polygon's full extent as the output domain
        ext = plg.getExtent();

        // Compute aspect ratio so output pixels remain square when projected
        rat = (ext.YMax - ext.YMin) / (ext.XMax - ext.XMin);

        // Create and initialise the in-memory raster output layer
        dst = new TGIS_LayerPixel();
        dst.setName("grid");
        // Build allocates the pixel buffer: true=in-memory, src.getCS()=CRS,
        // GRID_RESOLUTION=width, rounded height maintains square pixels
        dst.Build(true, src.getCS(), ext, GRID_RESOLUTION, (int)(Math.round(rat * GRID_RESOLUTION)));
        // Disable hill-shading - the interpolated values are not elevation data
        dst.getParams().getPixel().setGridShadow(false);

        // Run the long interpolation on a background thread so the Swing EDT
        // remains free to repaint the progress bar during computation
        new Thread(new Runnable() {
            @Override
            public void run() {
                // Default ramp start colour (overridden to transparent blue for heat maps)
                clr = TGIS_Color.getBlue();

                // Dispatch to the selected interpolation method
                if (rbIDW.isSelected()) {
                    // Inverse Distance Weighting
                    doIDW();
                } else
                if (rbKriging.isSelected()) {
                    // Geostatistical Kriging
                    doKriging();
                } else
                if (rbSplines.isSelected()) {
                    // Completely Regularized Splines
                    doSplines();
                } else
                if (rbHeatMap.isSelected())
                {
                    // Gaussian heat map weighted by TEMP field
                    doHeatmap(false);
                    // Transparent blue start so basemap shows through zero-density areas
                    clr = TGIS_Color.FromARGB((byte)0, (byte)0, (byte)0, (byte)255);
                }
                else
                if (rbConcentration.isSelected())
                {
                    // Gaussian concentration map (point density only)
                    doHeatmap(true);
                    clr = TGIS_Color.FromARGB((byte)0, (byte)0, (byte)0, (byte)255);
               }

                // Apply a three-stop colour ramp across the full value range.
                // Blue (low) -> Lime (mid) -> Red (high)
                dst.GenerateRamp(clr, TGIS_Color.getLime(), TGIS_Color.getRed(),
                        dst.getMinHeight(), (dst.getMaxHeight() - dst.getMinHeight()) / 2,
                        dst.getMaxHeight(), false,
                        (dst.getMaxHeight() - dst.getMinHeight()) / 100.0,
                        (dst.getMaxHeight() - dst.getMinHeight()) / 10.0,
                        null, false
                );

                // Clip the grid to the country boundary.  GetShape(6) is the 7th shape
                // (0-based); CreateCopy is required because setCuttingPolygon takes ownership.
                dst.setCuttingPolygon((TGIS_ShapePolygon)plg.GetShape(6).CreateCopy());
                // Ensure the interpolated grid renders above the basemap layers
                dst.setZOrder(1);
                // Add the generated grid to the viewer layer list
                GIS.Add(dst);

                // Zoom to display the full interpolated result
                GIS.FullExtent();

                // Re-enable the button now that the background work is done
                btnGenerate.setEnabled(true);
            }
        }).start();

    }//GEN-LAST:event_btnGenerateActionPerformed

    /**
     * Progress callback invoked by the interpolation engine at regular intervals.
     *
     * <p>TatukGIS busy event convention:
     * <ul>
     *   <li>{@code getPos() == 0}  => initialise (configure bar range)</li>
     *   <li>{@code getPos() < 0}   => operation finished (show maximum)</li>
     *   <li>{@code getPos() > 0}   => update bar to current position</li>
     * </ul>
     *
     * <p>{@code TGIS_BusyEvent} is implemented as an anonymous inner class in Java
     * because Java lacks direct delegate/closure support for event callbacks.
     */
    private void doBusyEvent(Object _sender, TGIS_BusyEventArgs _e){
        if (_e.getPos() < 0) {
            // Finished: show full bar
            progressBar1.setValue(progressBar1.getMaximum());
        } else {
            if (_e.getPos() == 0) {
                // Initialise: configure the range for this operation
                progressBar1.setMinimum(0);
                progressBar1.setMaximum((int)_e.getEndPos());
                progressBar1.setValue(0);
            }
            else {
                // Update the bar on every positive step
                if (_e.getPos() > 0) {
                    progressBar1.setValue((int)_e.getPos());
                }
            }
        }
    }

    /**
     * Runs Inverse Distance Weighting (IDW) interpolation.
     *
     * <p>IDW estimates each output cell as a weighted average of all sample points,
     * where the weight is 1/distance^Exponent.  {@code setExponent(3.0)} produces
     * a more localised surface with sharper peaks than the default 2.0.
     *
     * <p>Enable windowed mode to limit contributors and improve performance on
     * large datasets:
     * <pre>
     *   vtg.setWindowed(true);
     *   vtg.setRadius((ext.XMax - ext.XMin) / 5.0);
     * </pre>
     *
     * <p>The {@code TGIS_BusyEvent} is wired via an anonymous inner class
     * that delegates to {@link #doBusyEvent}.
     */
    private void doIDW(){
        TGIS_InterpolationIDW vtg;

        vtg = new TGIS_InterpolationIDW();

        // For windowed version of this method you need to set Windowed=True
        // and at least the Radius, e.g.:
        //   vtg.setWindowed(true);
        //   vtg.setRadius((ext.XMax - ext.XMin) / 5.0);

        // Wire the progress callback via anonymous inner class
        vtg.setBusyEvent(new TGIS_BusyEvent() {
            @Override
            public void Invoke(Object o, TGIS_BusyEventArgs tgsb) {
                doBusyEvent(o, tgsb);
            }
        });

        // Exponent 3.0 gives sharper local peaks than the default 2.0
        vtg.setExponent(3.0);
        // Generate the IDW grid: read FIELD_VALUE from src, write to dst
        vtg.Generate(src, src.getExtent(), FIELD_VALUE, dst, dst.getExtent());
    }

    /**
     * Runs Ordinary Kriging interpolation with a user-selectable semivariogram model.
     *
     * <p>Kriging models spatial autocorrelation through a semivariogram and produces
     * a statistically optimal (Best Linear Unbiased) estimate at each cell.
     * The semivariogram model governs spatial dependence structure:
     * <ul>
     *   <li>Power Law    - scale-free power relationship (default)</li>
     *   <li>Exponential  - exponential decay of spatial correlation</li>
     *   <li>Gaussian     - smooth Gaussian bell-curve decay</li>
     *   <li>Spherical    - linear then flat, common in geology</li>
     *   <li>Circular     - circular model</li>
     *   <li>Linear       - simple linear model</li>
     * </ul>
     */
    private void doKriging(){
        TGIS_InterpolationKriging vtg;

        vtg = new TGIS_InterpolationKriging();

        // For windowed version of this method you need to set Windowed=True
        // and at least the Radius, e.g.:
        //   vtg.setWindowed(true);
        //   vtg.setRadius((ext.XMax - ext.XMin) / 5.0);

        // Wire the progress callback via anonymous inner class
        vtg.setBusyEvent(new TGIS_BusyEvent() {
            @Override
            public void Invoke(Object o, TGIS_BusyEventArgs tgsb) {
                doBusyEvent(o, tgsb);
            }
        });

        // Select the semivariogram model based on the combo box choice
        switch (cbSemivariance.getSelectedIndex())
        {
            case 0: vtg.setSemivariance(new TGIS_SemivariancePowerLaw()); break;
            case 1: vtg.setSemivariance(new TGIS_SemivarianceExponential()); break;
            case 2: vtg.setSemivariance(new TGIS_SemivarianceGaussian()); break;
            case 3: vtg.setSemivariance(new TGIS_SemivarianceSpherical()); break;
            case 4: vtg.setSemivariance(new TGIS_SemivarianceCircular()); break;
            case 5: vtg.setSemivariance(new TGIS_SemivarianceLinear()); break;
        }

        // Generate the Kriging interpolation grid
        vtg.Generate(src, src.getExtent(), FIELD_VALUE, dst, dst.getExtent());
    }

    /**
     * Runs Completely Regularized Splines (CRS) interpolation.
     *
     * <p>CRS fits a smooth surface through the sample points using radial basis
     * functions.  {@code setTension(1e-9)} gives a minimum-curvature (very smooth)
     * result; increase it if the surface shows unwanted oscillations in data-sparse
     * regions.
     */
    private void doSplines(){
        TGIS_InterpolationSplines vtg;

        vtg = new TGIS_InterpolationSplines();

        // For windowed version of this method you need to set Windowed=True
        // and at least the Radius, e.g.:
        //   vtg.setWindowed(true);
        //   vtg.setRadius((ext.XMax - ext.XMin) / 5.0);

        // Wire the progress callback via anonymous inner class
        vtg.setBusyEvent(new TGIS_BusyEvent() {
            @Override
            public void Invoke(Object o, TGIS_BusyEventArgs tgsb) {
                doBusyEvent(o, tgsb);
            }
        });

        // Tension=1e-9 produces a very smooth minimum-curvature surface
        vtg.setTension(1e-9);
        // Generate the Completely Regularized Splines interpolation grid
        vtg.Generate(src, src.getExtent(), FIELD_VALUE, dst, dst.getExtent());
    }

    /**
     * Runs Gaussian Heat Map or Concentration Map generation.
     *
     * <p>Both modes use {@link TGIS_GaussianHeatmap}; the difference is:
     * <ul>
     *   <li>Heat Map ({@code _concentration=false}): each point spreads its TEMP
     *       value through a Gaussian kernel; high-value points produce brighter
     *       hotspots.</li>
     *   <li>Concentration Map ({@code _concentration=true}): ignores the TEMP field;
     *       every point contributes equally to count spatial density.</li>
     * </ul>
     *
     * <p>{@code EstimateRadius} computes the optimal kernel bandwidth from the
     * average nearest-neighbour distance (3-sigma bandwidth); halving it produces
     * a finer, more peaked result.
     *
     * @param _concentration true to generate a Concentration Map (density only);
     *                       false to generate a Heat Map (field values weighted)
     */
    private void doHeatmap(boolean _concentration){
        TGIS_GaussianHeatmap vtg;
        String fld;

        vtg = new TGIS_GaussianHeatmap();

        // Coordinate.None uses point centroids as-is (no centroid offset)
        vtg.setCoordinate(TGIS_VectorToGridCoordinate.None);
        // Concentration Map: supply empty field name so only point presence counts
        if (_concentration)
         fld = "";
        else
         fld = FIELD_VALUE;

        // Wire the progress callback via anonymous inner class
        vtg.setBusyEvent(new TGIS_BusyEvent() {
            @Override
            public void Invoke(Object o, TGIS_BusyEventArgs tgsb) {
                doBusyEvent(o, tgsb);
            }
        });

        // Estimate 3-sigma Gaussian kernel radius from the average nearest-neighbour
        // distance in the source layer
        vtg.EstimateRadius(src, src.getExtent(), dst);
        // Halve the estimated radius for a more localised, peaked result
        vtg.setRadius(vtg.getRadius() / 2.0);
        // Generate the Heat/Concentration Map grid
        vtg.Generate(src, src.getExtent(), fld, dst, dst.getExtent());
    }


