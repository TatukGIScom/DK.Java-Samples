    /**
     * Toggles the hill-shading (GridShadow) effect on the DEM layer.
     * Hill-shading simulates directional lighting to enhance terrain perception.
     * Java property access: {@code getParams().getPixel().setGridShadow(...)}.
     */
    private void btnShadowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShadowActionPerformed
        TGIS_LayerPixel lp;

        // getItems().getItems(0) retrieves the first layer in the viewer
        lp = (TGIS_LayerPixel)GIS.getItems().getItems(0);
        // Toggle the shadow flag
        lp.getParams().getPixel().setGridShadow(!lp.getParams().getPixel().getGridShadow());
        GIS.InvalidateWholeMap();
    }//GEN-LAST:event_btnShadowActionPerformed

