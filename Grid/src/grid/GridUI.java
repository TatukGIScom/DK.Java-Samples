    /**
     * Queries the raw DEM elevation value at the geographic location under the
     * mouse and displays it in the altitude label.
     *
     * <p>How it works:
     * <ol>
     *   <li>{@code GIS.ScreenToMap} converts the AWT screen point to geographic coords.</li>
     *   <li>{@code TGIS_LayerPixel.Locate} queries the raster at that point and fills
     *       the {@code VarParameter} wrappers:
     *       <ul>
     *         <li>{@code rgb}     - the rendered colour at the queried pixel</li>
     *         <li>{@code natives} - raw band values; {@code [0]} = elevation in metres</li>
     *         <li>{@code transp}  - whether the pixel is transparent (outside data)</li>
     *       </ul>
     *   </li>
     *   <li>The raw elevation is shown in {@code lbAltitude}.</li>
     * </ol>
     *
     * <p>{@code VarParameter<T>} is used because Java cannot pass primitives or objects
     * by reference; the wrapper provides a mutable container for output values.
     */
    private void GISMouseMoved(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_GISMouseMoved
        TGIS_Point ptg;
        TGIS_LayerPixel lp;
        VarParameter<TGIS_Color> rgb;       // Output: rendered colour at queried pixel
        VarParameter<double[]> natives;     // Output: raw band values ([0] = elevation)
        VarParameter<Boolean> transp;       // Output: transparency flag

        // Initialise VarParameter wrappers (required for out-parameter semantics)
        rgb = new VarParameter<>();
        natives = new VarParameter<>();
        transp = new VarParameter<>();

        // Avoid querying while the map is being redrawn
        if ( GIS.getInPaint() ) return ;

        // Convert AWT screen coordinates to geographic map coordinates
        ptg = GIS.ScreenToMap(new TPoint(evt.getX(), evt.getY()));
        lp = (TGIS_LayerPixel)GIS.getItems().getItems(0);

        // Locate returns true when the point falls inside the raster extent
        if (lp.Locate(ptg, rgb, natives, transp)) {
            // natives.Value[0] is the raw elevation in the DEM's native unit (metres)
            lbAltitude.setText("Altitude: " + natives.Value[0]);
        } else {
            lbAltitude.setText("Altitude: Unknown");
        }
    }//GEN-LAST:event_GISMouseMoved

