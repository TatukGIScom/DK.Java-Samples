    /**
     * Handles projection selection from the combo box.
     *
     * <p>Core on-the-fly reprojection pattern:</p>
     * <ol>
     *   <li>Retrieve the WKT name of the selected projection method.</li>
     *   <li>Look up the geographic datum (EPSG 4030 = WGS 84 unscaled),
     *       linear unit (Metre), and projection method from the global
     *       TatukGIS catalogues.</li>
     *   <li>Construct a {@link TGIS_CSProjectedCoordinateSystem} by combining
     *       those three components. {@code DefaultParams()} supplies sensible
     *       default values (central meridian, standard parallels, etc.) so
     *       no manual parameter entry is required.  EPSG = -1 marks the CRS
     *       as user-defined rather than a registered EPSG entry.</li>
     *   <li>Assign the new CRS via {@code GIS.setCS()}.  The viewer reprojects
     *       all loaded layers in memory without reloading source data.</li>
     *   <li>Call {@code GIS.FullExtent()} to re-zoom to the world extent
     *       expressed in the new coordinate system.</li>
     * </ol>
     *
     * <p>{@code Lock()} / {@code Unlock()} prevent intermediate repaints
     * between the CRS assignment and the extent reset, eliminating flicker.</p>
     *
     * @param evt the action event fired by the combo box
     */
    private void comboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboBoxActionPerformed
        // Retrieve the WKT name of the projection chosen by the user.
        String proj = comboBox.getSelectedItem().toString();

        // WGS 84 unscaled — the standard geographic datum base for on-the-fly
        // CRS construction without committing to a specific ellipsoid scaling.
        TGIS_CSGeographicCoordinateSystem ogcs = TGIS_Utils.getCSGeographicCoordinateSystemList().ByEPSG(4030);

        // Metre — the most common linear unit for projected coordinate systems.
        TGIS_CSUnits ounit = TGIS_Utils.getCSUnitsList().ByWKT("METER");

        // Look up the projection method object from the global catalogue.
        TGIS_CSProjAbstract oproj = TGIS_Utils.getCSProjList().ByWKT(proj);

        // Build a complete projected CRS dynamically.
        // EPSG = -1 : user-defined, not registered in the EPSG database.
        // "Test"    : temporary display name for this CRS.
        // DefaultParams provides canonical parameter values (central meridian,
        // standard parallels, etc.) for the projection so no manual input
        // is required.
        TGIS_CSCoordinateSystem ocs = new TGIS_CSProjectedCoordinateSystem(
                     -1, "Test",
                     ogcs.getEPSG(), ounit.getEPSG(), oproj.getEPSG(),
                     TGIS_Utils.getCSProjectedCoordinateSystemList().DefaultParams(oproj.getEPSG())
                   );

        // Lock prevents repaints during the combined CS + extent update.
        GIS.Lock();
        try
        {
            // Assigning the CRS triggers on-the-fly reprojection of all layers.
            GIS.setCS(ocs);

            // Re-zoom to the full world extent expressed in the new CRS.
            GIS.FullExtent();

            // Note: unlike the other ports this sample does not swallow exceptions
            // from incompatible projections; they surface as runtime errors.
        }
        finally
        {
            GIS.Unlock();
        }
    }//GEN-LAST:event_comboBoxActionPerformed


