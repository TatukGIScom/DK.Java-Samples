    /**
     * Populates the projection combo box with all known projection names and
     * opens the bundled world map project.
     *
     * <p>Unlike the other language ports this method adds every projection
     * from the catalogue (not just "standard" ones) because the Java combo
     * box is editable and the full list is useful for demonstration purposes.</p>
     *
     * <p>{@code GIS.InvalidateWholeMap()} forces a full repaint after the map
     * is opened, and {@code GIS.FullExtent()} zooms to the global extent in
     * whatever CRS the project specifies.</p>
     */
    @SuppressWarnings("unchecked")
    private void initOwn(){
        int i;
        // Add every projection WKT name to the combo box so the user can
        // explore the complete TatukGIS projection catalogue.
        for (i = 0; i < TGIS_Utils.getCSProjList().Count(); i++)
            {
                comboBox.addItem(TGIS_Utils.getCSProjList().getProjection(i).getWKT());
            }

        // Open the bundled world map; path is resolved by GisSamplesDataDirDownload.
        GIS.Open(TGIS_Utils.GisSamplesDataDirDownload() + "/Samples/Projects/world.ttkproject");

        // Force a full repaint so all layers are rendered immediately.
        GIS.InvalidateWholeMap();

        // Zoom to the world extent in the project's default CRS.
        GIS.FullExtent();
    }

